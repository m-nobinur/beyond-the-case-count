# PDF for the report (the LaTeX caption replaces the plot title); PNG with title for the README.
save_fig <- function(plot, name, width = 6.3, height = 3.8) {
  ggsave(P("output", "figures", paste0(name, ".png")), plot, width = width, height = height, dpi = 200, bg = "white")
  if (!inherits(plot, "patchwork")) plot <- plot + labs(title = NULL)
  ggsave(P("output", "figures", paste0(name, ".pdf")), plot, width = width, height = height, device = cairo_pdf)
  invisible(plot)
}

# Write a LaTeX table that the report \input{}s directly (numbers never hand-typed).
save_tab <- function(df, name, caption, label = name, digits = 2, align = NULL,
                     font = "small", notes = NULL, longtable = FALSE, escape = TRUE, ...) {
  if (!escape) {  # raw-LaTeX tables: a bare % would start a LaTeX comment
    esc_pct <- function(x) gsub("(?<!\\\\)%", "\\\\%", x, perl = TRUE)
    names(df) <- esc_pct(names(df))
    df <- mutate(df, across(where(is.character), esc_pct))
  }
  k <- kbl(df, format = "latex", booktabs = TRUE, digits = digits, caption = caption,
           label = label, align = align, linesep = "", longtable = longtable, escape = escape, ...) %>%
    kable_styling(latex_options = c(if (!longtable) c("hold_position", "scale_down"), if (longtable) "repeat_header"),
                  font_size = NULL)
  if (!is.null(notes)) k <- footnote(k, general = notes, general_title = "Note.", threeparttable = TRUE,
                                     footnote_as_chunk = TRUE, escape = escape)
  txt <- as.character(k)
  if (!longtable) txt <- sub("\\\\centering", paste0("\\\\centering\\\\", font), txt)
  writeLines(txt, P("output", "tables", paste0(name, ".tex")))
  invisible(df)
}

# Macro registry: each script writes output/macros/<script>.tex with \newcommand{\Name}{value}
.macros <- new.env()
macro <- function(name, value) {
  stopifnot(grepl("^[A-Za-z]+$", name))
  assign(name, as.character(value), envir = .macros)
}
write_macros <- function(file) {
  nm <- sort(ls(.macros))
  val <- vapply(nm, function(n) get(n, envir = .macros), "")
  # p/q-value macros (name ends in P, p or q) become full expressions, e.g. "$p = 0.004$" or "$q < 0.001$"
  is_pv <- grepl("(P|p|q)$", nm) & grepl("^(\\$<\\$0\\.001|[01]\\.\\d{3})$", val)
  sym <- ifelse(grepl("q$", nm), "q", "p")
  val[is_pv] <- ifelse(grepl("^\\$", val[is_pv]), sprintf("$%s < 0.001$", sym[is_pv]), sprintf("$%s = %s$", sym[is_pv], val[is_pv]))
  lines <- sprintf("\\newcommand{\\%s}{%s}", nm, val)
  writeLines(c("% generated by R — do not edit", lines), P("output", "macros", paste0(file, ".tex")))
  rm(list = nm, envir = .macros)
}

